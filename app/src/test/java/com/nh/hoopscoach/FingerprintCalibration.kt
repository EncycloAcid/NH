class FingerprintCalibration {
    private data class Multipliers(
        val shots: Double,
        val three: Double,
        val draw: Double,
        val ftAdj: Double,
        val orb: Double,
        val drb: Double,
        val ast: Double,
        val stl: Double,
        val blk: Double,
        val tov: Double,
        val foul: Double,
    ) {
        fun fields() = listOf(shots, three, draw, ftAdj, orb, drb, ast, stl, blk, tov, foul)

        companion object {
            fun from(fp: Fingerprint) = Multipliers(
                fp.shots, fp.three, fp.draw, fp.ftAdj, fp.orb, fp.drb, fp.ast, fp.stl, fp.blk, fp.tov, fp.foul,
            )
        }
    }

    private data class Targets(
        val shots: Double,
        val three: Double,
        val draw: Double,
        val ft: Double,
        val orb: Double,
        val drb: Double,
        val ast: Double,
        val stl: Double,
        val blk: Double,
        val tov: Double,
        val foul: Double,
    ) {
        fun fields() = linkedMapOf(
            "shots" to shots, "three" to three, "draw" to draw, "ft" to ft,
            "orb" to orb, "drb" to drb, "ast" to ast, "stl" to stl,
            "blk" to blk, "tov" to tov, "foul" to foul,
        )
    }

    private data class Sample(val target: Double, val sim: Double, val minutes: Double)

    private val statNames = listOf("shots", "three", "draw", "ft", "orb", "drb", "ast", "stl", "blk", "tov", "foul")

    private fun calibrationFile(): File {
        val root = File(System.getProperty("user.dir"))
        return listOf(
            File(root, "app/src/main/resources/eras"),
            File(root, "src/main/resources/eras"),
        ).first { it.isDirectory }.resolve("today_fingerprint.tsv")
    }

    private fun readCalibration(): Map<String, Multipliers> {
        val file = calibrationFile()
        if (!file.isFile) return emptyMap()
        return file.readLines().filter { it.isNotBlank() && !it.startsWith("#") }.associate { line ->
            val fields = line.split("|")
            fields[0] to Multipliers(
                fields[1].toDouble(), fields[2].toDouble(), fields[3].toDouble(), fields[4].toDouble(),
                fields[5].toDouble(), fields[6].toDouble(), fields[7].toDouble(), fields[8].toDouble(),
                fields[9].toDouble(), fields[10].toDouble(), fields[11].toDouble(),
            )
        }
    }

    private fun writeCalibration(values: Map<String, Multipliers>) {
        calibrationFile().writeText(buildString {
            appendLine("# Empirical per-player calibration; generated by CALIBRATE=1 ./gradlew :app:testDebugUnitTest --tests com.nh.hoopscoach.FingerprintCalibration --console=plain")
            appendLine("# name|shots|three|draw|ftAdj|orb|drb|ast|stl|blk|tov|foul")
            for ((name, rates) in values.toSortedMap()) {
                append(name)
                for (value in rates.fields()) append("|").append(String.format(Locale.US, "%.4f", value))
                appendLine()
            }
        })
    }

    private fun withMultipliers(fp: Fingerprint, m: Multipliers) = Fingerprint(
        shots = m.shots,
        three = m.three,
        draw = m.draw,
        ftAdj = m.ftAdj,
        orb = m.orb,
        drb = m.drb,
        ast = m.ast,
        stl = m.stl,
        blk = m.blk,
        tov = m.tov,
        foul = m.foul,
        age = fp.age,
        mpg = fp.mpg,
        season = fp.season,
        v = 2,
    )

    private fun targets(lg: League): Map<String, Targets> {
        val candidates = lg.players.mapNotNull { p ->
            EraData.career(p.name)?.takeIf { it.mp > 0 && it.fga > 0 }?.let { p.name to it }
        }
        val fta = candidates.sumOf { it.second.fta }.toDouble()
        val leagueFt = if (fta > 0.0) candidates.sumOf { it.second.ft }.toDouble() / fta else 0.78

        fun perMinute(recent: Double, career: Double, mp: Int, rMp: Double): Double {
            val careerRate = career / mp
            return if (rMp <= 0.0) careerRate else (recent + 1000.0 * careerRate) / (rMp + 1000.0)
        }

        return candidates.associate { (name, c) ->
            val c3 = (c.fg3a.toDouble() / c.fga).coerceIn(0.01, 0.95)
            val cd = c.fta.toDouble() / c.fga
            val careerFt = if (c.fta > 0) c.ft.toDouble() / c.fta else leagueFt
            val rMp = c.rMp
            val three = if (rMp <= 0.0) c3 / (1.0 - c3) else {
                val share = (c.rFg3a + 150.0 * c3) / (c.rFga + 150.0)
                share / (1.0 - share)
            }
            val draw = if (rMp <= 0.0) cd else (c.rFta + 150.0 * cd) / (c.rFga + 150.0)
            val ft = if (rMp <= 0.0) careerFt else (c.rFt + 150.0 * careerFt) / (c.rFta + 150.0)
            name to Targets(
                shots = perMinute(c.rFga + 0.44 * c.rFta, c.fga + 0.44 * c.fta, c.mp, rMp),
                three = three,
                draw = draw,
                ft = ft,
                orb = perMinute(c.rOrb, c.orb.toDouble(), c.mp, rMp),
                drb = perMinute(c.rDrb, c.drb.toDouble(), c.mp, rMp),
                ast = perMinute(c.rAst, c.ast.toDouble(), c.mp, rMp),
                stl = perMinute(c.rStl, c.stl.toDouble(), c.mp, rMp),
                blk = perMinute(c.rBlk, c.blk.toDouble(), c.mp, rMp),
                tov = perMinute(c.rTov, c.tov.toDouble(), c.mp, rMp),
                foul = perMinute(c.rPf, c.pf.toDouble(), c.mp, rMp),
            )
        }
    }

    private fun simRates(line: StatLine): Map<String, Double> {
        val minutes = line.sec / 60.0
        if (minutes <= 0.0) return emptyMap()
        val rates = linkedMapOf(
            "shots" to (line.fga + 0.44 * line.fta) / minutes,
            "draw" to line.fta.toDouble() / line.fga.coerceAtLeast(1),
            "orb" to line.orb / minutes,
            "drb" to line.drb / minutes,
            "ast" to line.ast / minutes,
            "stl" to line.stl / minutes,
            "blk" to line.blk / minutes,
            "tov" to line.tov / minutes,
            "foul" to line.pf / minutes,
        )
        if (line.fga > line.tpa) rates["three"] = line.tpa.toDouble() / (line.fga - line.tpa)
        if (line.fta >= 40) rates["ft"] = line.ftm.toDouble() / line.fta
        return rates
    }

    private fun report(pass: Int, byStat: Map<String, List<Sample>>) {
        println("pass ${pass + 1}")
        for (stat in statNames) {
            val samples = byStat[stat].orEmpty().filter { it.target > 0.0 && it.sim.isFinite() }
            if (samples.isEmpty()) {
                println("$stat slope=0.0000 mean_ratio=0.0000 n=0")
                continue
            }
            val targetMean = samples.map { it.target }.average()
            val simMean = samples.map { it.sim }.average()
            val covariance = samples.sumOf { (it.target - targetMean) * (it.sim - simMean) }
            val variance = samples.sumOf { (it.target - targetMean) * (it.target - targetMean) }
            val slope = if (variance > 0.0) covariance / variance else 0.0
            val totalMinutes = samples.sumOf { it.minutes }
            val ratio = samples.sumOf { it.sim / it.target * it.minutes } / totalMinutes
            println("$stat slope=${"%.4f".format(Locale.US, slope)} mean_ratio=${"%.4f".format(Locale.US, ratio)} n=${samples.size}")
        }
    }

    private fun update(old: Multipliers, target: Targets, sim: Map<String, Double>): Multipliers {
        fun multiplier(name: String, current: Double, goal: Double): Double {
            val actual = sim[name] ?: return current
            if (actual == 0.0 || goal == 0.0 || !actual.isFinite()) return current
            return (current * (goal / actual).pow(0.8)).coerceIn(0.1, 10.0)
        }
        val ftAdj = sim["ft"]?.takeIf { target.ft > 0.0 && it > 0.0 && it.isFinite() }
            ?.let { old.ftAdj + 0.8 * (target.ft - it) } ?: old.ftAdj
        return Multipliers(
            shots = multiplier("shots", old.shots, target.shots),
            three = multiplier("three", old.three, target.three),
            draw = multiplier("draw", old.draw, target.draw),
            ftAdj = ftAdj,
            orb = multiplier("orb", old.orb, target.orb),
            drb = multiplier("drb", old.drb, target.drb),
            ast = multiplier("ast", old.ast, target.ast),
            stl = multiplier("stl", old.stl, target.stl),
            blk = multiplier("blk", old.blk, target.blk),
            tov = multiplier("tov", old.tov, target.tov),
            foul = multiplier("foul", old.foul, target.foul),
        )
    }

    @Test
    fun calibrate() {
        if (System.getenv("CALIBRATE") != "1") return
        val passes = (System.getenv("CALIBRATION_PASSES") ?: "6").toInt()
        val startPass = (System.getenv("CALIBRATION_START") ?: "0").toInt()
        var multipliers = readCalibration()

        repeat(passes) { offset ->
            val pass = startPass + offset
            val draft = ProTest().toDraft(21)
            Rng.r = Random(100 + pass)
            val lg = ProLeague.create(draft)
            val targetByName = targets(lg)
            for (p in lg.players) {
                val fp = p.fingerprint ?: continue
                val m = multipliers[p.name] ?: Multipliers.from(fp)
                multipliers = multipliers + (p.name to m)
                p.fingerprint = withMultipliers(fp, m)
            }

            var guard = 0
            while (lg.phase == Phase.OFFSEASON && guard++ < 20) ProCareer.next(lg)
            guard = 0
            while (lg.phase == Phase.REGULAR && guard++ < 260) Sim.playDay(lg)

            val byStat = statNames.associateWith { mutableListOf<Sample>() }
            for (p in lg.players) {
                val target = targetByName[p.name] ?: continue
                val minutes = p.stats.sec / 60.0
                if (minutes < 500.0) continue
                val sim = simRates(p.stats)
                for ((name, goal) in target.fields()) {
                    val actual = sim[name] ?: continue
                    if (goal > 0.0 && actual.isFinite()) byStat.getValue(name) += Sample(goal, actual, minutes)
                }
                val old = multipliers[p.name] ?: p.fingerprint?.let { Multipliers.from(it) } ?: continue
                multipliers = multipliers + (p.name to update(old, target, sim))
            }
            report(pass, byStat)
        }
        writeCalibration(multipliers)
        println("wrote ${calibrationFile().absolutePath}")
    }
}
