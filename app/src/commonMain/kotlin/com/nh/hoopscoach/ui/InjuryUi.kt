/** [t]'s injury report: who's out, with what, and for how long. Nothing when everyone is healthy. */
@Composable
fun InjuryReport(vm: GameViewModel, lg: League, t: Team) {
    val hurt = Injuries.report(lg, t)
    if (hurt.isEmpty()) return
    Section("Injury report · ${hurt.size}")
    GroupList(hurt, inset = 70.dp) { p ->
        ListRow(onClick = { vm.openPlayer(p.id) }) {
            PlayerJersey(p, t, 40.dp)
            Spacer(Modifier.width(12.dp))
            Column(Modifier.weight(1f)) {
                Text(p.name, style = T.bodyB, color = P.ink, maxLines = 1, overflow = TextOverflow.Ellipsis)
                Text(Injuries.tag(p), style = T.small, color = injuryColor(p), maxLines = 2)
            }
            Tag("INJ", P.bad)
        }
    }
    if (lg.ollama.enabled && lg.ollama.injuryReports) {
        AiInjuryAnalysisCard(lg, hurt.first(), t)
    }
}

/** Tactical medical breakdown and next-man-up outlook generated by AI. */
@Composable
fun AiInjuryAnalysisCard(lg: League, player: Player, team: Team) {
    var analysis by remember(player.id, player.injGames) { mutableStateOf<Ollama.InjuryAnalysis?>(null) }
    var loading by remember(player.id, player.injGames) { mutableStateOf(false) }
    val scope = rememberCoroutineScope()

    LaunchedEffect(player.id, player.injGames) {
        val cacheKey = "injury_${player.id}_${player.injGames}_${lg.ollama.activeModelName}"
        Ollama.Cache.get<Ollama.InjuryAnalysis>(cacheKey)?.let { analysis = it }
    }

    Column(
        Modifier
            .fillMaxWidth()
            .padding(horizontal = 14.dp, vertical = 6.dp)
            .clip(RoundedCornerShape(12.dp))
            .background(P.surface2)
            .padding(12.dp),
    ) {
        Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
            Text("MEDICAL OUTLOOK", style = T.label, color = P.accent, modifier = Modifier.weight(1f))
            AiBadge(analysis?.isAi == true, lg.ollama.providerDisplayName, fallbackReason = analysis?.fallbackReason.orEmpty())
            if (analysis == null && !loading) {
                SmallButton("Generate Breakdown", primary = true) {
                    loading = true
                    scope.launch {
                        val res = Ollama.generateInjuryAnalysis(lg.ollama, lg, team, player)
                        loading = false
                        res.onSuccess { analysis = it }
                    }
                }
            }
        }
        if (loading) {
            Spacer(Modifier.height(6.dp))
            Text("AI Medical Staff is compiling recovery outlook...", style = T.small, color = P.accent)
        } else if (analysis != null) {
            val a = analysis!!
            Spacer(Modifier.height(6.dp))
            Text(a.headline, style = T.bodyB, color = P.ink)
            Spacer(Modifier.height(4.dp))
            Text("• Recovery: ${a.severityOutlook}", style = T.small, color = P.sub)
            Spacer(Modifier.height(2.dp))
            Text("• Next Man Up: ${a.nextManUpStrategy}", style = T.small, color = P.sub)
            Spacer(Modifier.height(4.dp))
            if (a.quote.isNotBlank()) Text("\u201c${a.quote}\u201d", style = T.small.copy(fontStyle = androidx.compose.ui.text.font.FontStyle.Italic), color = P.faint)
        }
    }
}

/** The league's notable injuries, for the News page. */
@Composable
fun LeagueInjuries(vm: GameViewModel, lg: League) {
    val hurt = Injuries.league(lg).take(12)
    if (hurt.isEmpty()) return
    Section("Around the league: injuries")
    GroupList(hurt, inset = 70.dp) { (p, t) ->
        ListRow(onClick = { vm.openPlayer(p.id) }) {
            PlayerJersey(p, t, 40.dp)
            Spacer(Modifier.width(12.dp))
            Column(Modifier.weight(1f)) {
                Text("${p.name} · ${t.abbr}", style = T.bodyB, color = P.ink, maxLines = 1, overflow = TextOverflow.Ellipsis)
                Text(Injuries.tag(p), style = T.small, color = injuryColor(p), maxLines = 2, modifier = Modifier.padding(top = 1.dp))
            }
        }
    }
}

/** How bad it is, at a glance: amber for day-to-day, red for anything longer. */
@Composable
fun injuryColor(p: com.nh.hoopscoach.game.Player): androidx.compose.ui.graphics.Color = if (p.injGames <= 3 && p.injTotal <= 3) P.warn else P.bad

/** The user's team is defending a title: what it's chasing and how it's going. */
@Composable
fun TitleDefenseCard(lg: League) {
    val d = com.nh.hoopscoach.game.TitleDefense.userDefending(lg) ?: return
    if (lg.phase != com.nh.hoopscoach.game.Phase.REGULAR && lg.phase != com.nh.hoopscoach.game.Phase.PLAYOFFS && lg.phase != com.nh.hoopscoach.game.Phase.CONF_TOURNEY && lg.phase != com.nh.hoopscoach.game.Phase.NCAA) return
    val u = lg.user
    Spacer(Modifier.height(6.dp))
    Panel(color = P.hero) {
        Text(if (d.streak >= 2) "${com.nh.hoopscoach.game.TitleDefense.runWords(d.streak).uppercase()} · DEFENDING CHAMPIONS" else "DEFENDING CHAMPIONS", style = T.label, color = heroKicker)
        Text("Chasing ${com.nh.hoopscoach.game.TitleDefense.chasing(d.streak)}", style = T.head, color = P.onHero)
        Text("${u.record} so far. Everyone circles your game on their schedule.", style = T.small, color = P.onHero.copy(alpha = 0.9f))
    }
}

/** The big nights in the next few days, league-wide: Christmas, national TV, top-10 showdowns, rivalry games. */
@Composable
fun MarqueeCard(vm: GameViewModel, lg: League) {
    val games = com.nh.hoopscoach.game.Marquee.upcoming(lg)
    if (games.isEmpty()) return
    Section("Big games")
    GroupList(games) { g ->
        val h = lg.team(g.home); val a = lg.team(g.away)
        val mine = g.involves(lg.userTeamId)
        ListRow(onClick = { vm.push(Route.TeamPage(if (mine) lg.team(g.opp(lg.userTeamId)).id else h.id)) }) {
            TeamBadge(a, 30.dp)
            Spacer(Modifier.width(6.dp))
            TeamBadge(h, 30.dp)
            Spacer(Modifier.width(10.dp))
            Column(Modifier.weight(1f)) {
                Text("${if (lg.pro) a.name.substringAfterLast(' ') else a.school} at ${if (lg.pro) h.name.substringAfterLast(' ') else h.school}", style = T.bodyB, color = P.ink, maxLines = 1, overflow = TextOverflow.Ellipsis)
                Text(if (g.day == lg.day) "Today" else "Day ${g.day}", style = T.small, color = P.sub)
            }
            Tag(com.nh.hoopscoach.game.Marquee.label(lg, g).uppercase(), if (mine) P.accent else P.gold)
        }
    }
}

/** The user's coaching rivals, for the Career screen. */
@Composable
fun CoachRivalsCard(lg: League) {
    val rivals = com.nh.hoopscoach.game.CoachRivals.rivals(lg)
    if (rivals.isEmpty()) return
    Section("Coaching rivals")
    GroupList(rivals) { r ->
        val c = lg.coaches.firstOrNull { it.id == r.coachId }
        ListRow {
            Column(Modifier.weight(1f)) {
                Text(c?.name ?: "A former rival", style = T.bodyB, color = P.ink)
                Text("${lg.teams.getOrNull(c?.teamId ?: -1)?.let { if (lg.pro) it.name else it.school } ?: "Out of coaching"} · you're ${r.w}-${r.l}" + if (r.big > 0) " · ${r.big} postseason meeting${if (r.big == 1) "" else "s"}" else "",
                    style = T.small, color = P.sub)
            }
            Tag(com.nh.hoopscoach.game.CoachRivals.heatLabel(r.heat).uppercase(), if (r.heat >= 6) P.bad else P.warn)
        }
    }
}

/**
 * The user's standing with the compliance office: how far above market his deals run, the warnings on
 * file, the odds of an investigation this offseason, sanctions in force, and the option to self-report.
 */
@Composable
fun ComplianceCard(vm: GameViewModel, lg: League) {
    val C = com.nh.hoopscoach.game.Compliance
    if (!C.active(lg)) return
    val ratio = C.overpay(lg)
    val level = C.level(ratio)
    val risk = C.risk(lg)
    val sanctions = com.nh.hoopscoach.game.WorldEvents.sanctionLine(lg, lg.user)
    var confirm by androidx.compose.runtime.remember { androidx.compose.runtime.mutableStateOf(false) }
    val color = when (level) {
        com.nh.hoopscoach.game.Compliance.Level.CLEAN -> P.good
        com.nh.hoopscoach.game.Compliance.Level.WATCHED -> P.warn
        com.nh.hoopscoach.game.Compliance.Level.REVIEW -> P.warn
        com.nh.hoopscoach.game.Compliance.Level.RED -> P.bad
    }
    Section("Compliance")
    Panel {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Text(level.label, style = T.head, color = color, modifier = Modifier.weight(1f))
            Tag("${(ratio * 100).toInt()}% OF MARKET", color)
        }
        Text(level.note, style = T.small, color = P.sub, modifier = Modifier.padding(top = 2.dp))
        Spacer(Modifier.height(10.dp))
        Row(Modifier.fillMaxWidth()) {
            Stat("Warnings", "${lg.complianceWarnings}", Modifier.weight(1f), color = if (lg.complianceWarnings > 0) P.bad else P.ink, style = T.numSm)
            Stat("Investigation odds", C.riskLabel(risk), Modifier.weight(1f), color = if (risk >= 0.2) P.bad else if (risk > 0) P.warn else P.good, style = T.numSm)
        }
        if (sanctions.isNotEmpty()) Text(sanctions, style = T.small, color = P.bad, modifier = Modifier.padding(top = 8.dp))
        if (lg.selfReported == lg.season) Text("You self-reported this season: the risk of an investigation is much lower.", style = T.small, color = P.sub, modifier = Modifier.padding(top = 8.dp))
        else if (lg.complianceWarnings > 0 || level >= com.nh.hoopscoach.game.Compliance.Level.REVIEW) {
            Spacer(Modifier.height(10.dp))
            SecondaryButton("Self-report violations", Modifier.fillMaxWidth()) { confirm = true }
        }
        Spacer(Modifier.height(8.dp))
        Text("NIL offers above a recruit's ask become his salary, and they're what the compliance office watches. Paying market value clears warnings over time.",
            style = T.small, color = P.faint)
    }
    if (confirm) androidx.compose.material3.AlertDialog(
        onDismissRequest = { confirm = false }, containerColor = P.surface,
        title = { Text("Self-report?", style = T.head, color = P.ink) },
        text = { Text("You give up one scholarship next season and take a small hit to job security. Your warnings are cleared and an investigation this offseason becomes much less likely.", style = T.body, color = P.sub) },
        confirmButton = { androidx.compose.material3.TextButton({ confirm = false; vm.act { C.selfReport(it) } }) { Text("Self-report", color = P.bad) } },
        dismissButton = { androidx.compose.material3.TextButton({ confirm = false }) { Text("Not now", color = P.sub) } },
    )
}
